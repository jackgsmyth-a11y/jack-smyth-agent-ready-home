export const experimentScript = String.raw`
(() => {
  const root = document.querySelector('[data-experiment]'); if (!root) return;
  const kind = root.dataset.experiment;
  const $ = id => document.getElementById(id);
  const el = (tag, text, cls) => {const n=document.createElement(tag);if(text!==undefined)n.textContent=String(text);if(cls)n.className=cls;return n;};
  const notice = (target, text, error=false) => {const n=el('div',text,'notice'+(error?' error':''));target.replaceChildren(n);};
  async function request(path, body) {
    const r=await fetch('/api/experiments/'+path, {method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(body),signal:AbortSignal.timeout(125000)});
    const d=await r.json(); if(!r.ok){const err=new Error(d.error||'This step could not complete.');err.code=d.code;err.status=r.status;throw err;}
    return {data:d,status:r.status};
  }
  const picker = (container, dataKey, onPick) => {
    container.addEventListener('click',event=>{
      const a=event.target.closest('a['+dataKey+']');if(!a||event.ctrlKey||event.metaKey||event.shiftKey)return;
      event.preventDefault();if(onPick(a.getAttribute(dataKey))===false)return;
      for(const link of container.querySelectorAll('a'))link.setAttribute('aria-current',String(link===a));
      history.replaceState({},'',a.href);
    });
  };
  function renderIdea(idea) {
    const article=el('article',undefined,'surface');article.style.marginTop='22px';
    article.append(el('div',idea.categoryName||'Saved idea','eyebrow'),el('h3',idea.title));
    for(const [title,key] of [['Concept','concept'],['Execution','execution'],['Why it differs','distinction']]) {
      article.append(el('h4',title),el('p',idea[key]));
    }
    article.append(el('p','Generated by Flint, not Jack’s direct words. Review all factual and rights claims before use.','fine'));
    const copy=el('button','Copy idea','secondary');copy.type='button';
    copy.onclick=async()=>{try{await navigator.clipboard.writeText([idea.title,idea.concept,idea.execution,idea.distinction].join('\n\n'));copy.textContent='Copied';}catch{copy.textContent='Select the text above to copy';}};
    article.append(copy);return article;
  }
  if(kind==='facts-with-flair') {
    let examples=[],research={};
    fetch('/api/experiments/facts-with-flair/examples').then(r=>r.json()).then(d=>{examples=d.examples;research=d.research;}).catch(()=>{});
    function showExample(id) {
      const x=examples.find(x=>x.id===id);if(!x){location.href='?example='+encodeURIComponent(id);return;}
      $('example-title').textContent=x.productName;
      $('source-copy').textContent=x.sourceExcerpt;$('source-link').href=x.sourceUrl;
      $('rewrite-headline').textContent=x.headline;$('rewrite-copy').textContent=x.description;
      const spans=x.highlights.map((h,n)=>({start:x.description.indexOf(h.phrase),end:x.description.indexOf(h.phrase)+h.phrase.length,n})).filter(s=>s.start>=0).sort((a,b)=>a.start-b.start);
      const pieces=[];let cursor=0;
      for(const s of spans){if(s.start<cursor)continue;pieces.push(document.createTextNode(x.description.slice(cursor,s.start)));const mark=el('mark',x.description.slice(s.start,s.end));mark.setAttribute('aria-describedby','example-note-'+s.n);pieces.push(mark);cursor=s.end;}pieces.push(document.createTextNode(x.description.slice(cursor)));$('rewrite-copy').replaceChildren(...pieces);
      $('what-changed').textContent=x.meaningfulChange;
      $('fact-chips').replaceChildren(...x.facts.map(f=>el('span',f.label+' · '+f.value)));
      $('example-reasons').replaceChildren(...x.highlights.map((h,i)=>{const li=el('li');li.id='example-note-'+i;li.append(el('b',h.phrase),document.createElement('br'),document.createTextNode(h.explanation+' '));const r=research[h.researchId];if(r){const a=el('a',r.title+' ↗','fine');a.href=r.url;li.append(a);}return li;}));
      const meta=$('example-title').parentElement.querySelector('.quiet');if(meta)meta.textContent=x.retailer+' · checked '+x.sourceCheckedAt;
    }
    picker($('example-picker'),'data-example',showExample);
    let failedUrl='';
    $('product-url').addEventListener('input',()=>{if($('product-url').value!==failedUrl){$('paste-fallback').hidden=true;$('source-text').value='';}});
    $('flair-form').addEventListener('submit', async event => {
      event.preventDefault();const button=$('optimise');if(button.disabled)return;
      const url=$('product-url').value.trim();if(!url.startsWith('https://')){notice($('flair-status'),'Use a public HTTPS product URL.',true);return;}
      const sourceText=$('paste-fallback').hidden?undefined:$('source-text').value.trim();
      if(sourceText&&sourceText.length<80){notice($('flair-status'),'Paste at least 80 characters of actual product details.',true);return;}
      button.disabled=true;$('flair-output').hidden=true;
      try {
        notice($('flair-status'),'1 of 3 · Reading the page and extracting source facts…');
        let snapshot;
        try{snapshot=(await request('facts-with-flair/extract',{url,...(sourceText?{sourceText}:{})})).data;}
        catch(error){if(error.status===422){failedUrl=url;$('paste-fallback').hidden=false;}throw error;}
        notice($('flair-status'),'2 of 3 · Flint is drafting from the extracted facts…');
        const draft=(await request('facts-with-flair/draft',{sourceToken:snapshot.token})).data;
        notice($('flair-status'),'3 of 3 · Flint is reviewing six QA gates…');
        const result=(await request('facts-with-flair/review',{draftToken:draft.draftToken})).data;
        const out=$('flair-output');out.replaceChildren();out.hidden=false;
        const surface=el('article',undefined,'surface');surface.style.marginTop='24px';
        surface.append(el('div','Live Flint result · '+(sourceText?'pasted source':'extracted page'),'eyebrow'),el('h3',result.verdictLine||result.verdict));
        surface.append(el('p','Automated QA verdict: '+result.verdict+'. This checks the supplied source, not independent product truth.','quiet'));
        if(result.thinSource)surface.append(el('p','Thin source: meaningful differentiation may not be supported by this page alone. Review the failed gates and add verifiable product evidence before publishing.','notice'));
        for(const warning of snapshot.warnings||[])surface.append(el('p',warning,'fine'));
        surface.append(el('h3','Extracted specifications'));
        if(!(result.specBlock||[]).length)surface.append(el('p','No structured specifications were extracted. No attributes have been invented to fill the gap. You can paste clearer source specifications and run the workflow again.','notice'));
        const specs=el('div',undefined,'facts');for(const f of result.specBlock||[])specs.append(el('span',f.label+' · '+f.value));surface.append(specs);
        surface.append(el('h3','The narrative'),el('p',result.narrative,'reframed'));
        surface.append(el('h3','Why this one'));
        const why=el('ul',undefined,'reasons');for(const w of result.whyThisOne||[])why.append(el('li',w.text+(w.needsVerification?' [NEEDS VERIFICATION]':'')));surface.append(why);
        surface.append(el('h3','Agent-readable attributes'));
        const attrs=el('ul',undefined,'reasons');for(const text of result.agentSummary||[])attrs.append(el('li',text));surface.append(attrs);
        surface.append(el('h3','Six QA gates'));
        const gates=el('ul',undefined,'gates');
        for(const gate of result.gates||[]){const li=el('li');li.append(el('b',gate.number+'. '+gate.name+' — '+gate.status),el('div',gate.reason));for(const issue of gate.issues||[])li.append(el('p',issue.line+' → '+issue.fix,'quiet'));gates.append(li);}surface.append(gates);
        if(result.sweatNote)surface.append(el('p',result.sweatNote,'quiet'));
        const copy=el('button','Copy result','secondary');copy.type='button';copy.onclick=async()=>{try{await navigator.clipboard.writeText(JSON.stringify(result,null,2));copy.textContent='Copied';}catch{copy.textContent='Select the result text to copy';}};surface.append(copy);out.append(surface);
        notice($('flair-status'),result.verdict==='FAIL'?'Finished with failed QA gates. Review and fix the flagged claims before publishing.':'Draft and QA complete. Review the source and result before publishing.');
      }catch(error){notice($('flair-status'),error.message,true);}
      finally{button.disabled=false;}
    });
  } else {
    let categoryId=new URL(location.href).searchParams.get('category')||'beauty';
    let data=[],verified=false,busy=false,checkoutBusy=false,verificationBusy=false,historyBusy=false;
    const pendingClaims=new Map();
    const trackedPurchases=new Set();
    const receipt=()=> $('receipt').value.trim();
    const update=()=>{
      const locked=busy||checkoutBusy||verificationBusy;
      $('claim-idea').disabled=locked||!verified||!$('approve-credit').checked;
      $('approve-credit').disabled=locked||!verified;
      $('buy-pack').disabled=locked;$('verify-pack').disabled=locked;
      $('receipt').readOnly=locked;$('load-history').disabled=locked||historyBusy;
    };
    const resetApproval=()=>{$('approve-credit').checked=false;update();};
    function selectCategory(id) {
      if(busy||checkoutBusy)return false;const c=data.find(c=>c.id===id);if(!c)return false;categoryId=id;resetApproval();
      $('category-name').textContent=c.name;$('claim-category').textContent='One idea for '+c.name;
      $('category-name').parentElement.querySelector('.tag').textContent='Sample data · '+(c.latestMonth||'undated');
      $('category-patterns').replaceChildren(...c.patterns.map(p=>{const div=el('div',undefined,'theme');div.append(el('strong',p.theme),el('p',(p.keywords||[]).join(' · ')),el('span',p.frequency+' sample '+(p.frequency===1?'row':'rows'),'fine'));return div;}));
    }
    fetch('/api/experiments/leaderbored/categories').then(r=>r.json()).then(d=>{
      data=d.categories;
      const links=data.map(c=>{const a=el('a',c.name,'pick');a.href='?category='+c.id;a.setAttribute('data-category',c.id);a.setAttribute('aria-current',String(c.id===categoryId));return a;});
      $('category-picker').replaceChildren(...links);selectCategory(data.some(c=>c.id===categoryId)?categoryId:data[0]?.id);
      $('category-freshness').textContent=d.delivery==='existing-service'?'Loaded from the existing Leaderbored service. All category data remains labelled as sample reference data.':'The service could not be reached. Showing the bundled October 2026 sample snapshot—not live research.';
    }).catch(()=>{$('category-freshness').textContent='Showing the bundled October 2026 sample snapshot. Live service availability is unverified.';});
    picker($('category-picker'),'data-category',selectCategory);
    $('approve-credit').addEventListener('change',update);
    $('receipt').addEventListener('input',()=>{verified=false;resetApproval();$('credit-status').replaceChildren();});
    $('buy-pack').onclick=async()=>{
      if(busy||checkoutBusy)return;checkoutBusy=true;verified=false;resetApproval();$('checkout-result').replaceChildren();
      try{
        const {data:d}=await request('leaderbored/checkout',{categoryId,approved:true});
        const checkout=new URL(d.checkoutUrl);if(checkout.protocol!=='https:'||checkout.hostname!=='checkout.stripe.com')throw new Error('Unexpected checkout destination. No checkout was opened.');
        $('receipt').value=d.sessionId;verified=false;resetApproval();
        notice($('checkout-result'),'Checkout ready. Approve payment on Stripe, then return here and verify credits.');
        const link=el('a','Continue to Stripe ↗','btn');link.href=checkout.href;link.target='_blank';link.rel='noopener noreferrer';$('checkout-result').append(link);
      }catch(error){notice($('checkout-result'),error.message,true);}finally{checkoutBusy=false;update();}
    };
    $('verify-pack').onclick=async()=>{
      if(busy||verificationBusy)return;verificationBusy=true;verified=false;resetApproval();
      try{const sid=receipt();const {data:d}=await request('leaderbored/credits',{checkoutSessionId:sid});verified=!!d.creditsGranted&&d.creditsRemaining>0;if(verified&&typeof window.fbq==='function'&&!trackedPurchases.has(sid)){trackedPurchases.add(sid);window.fbq('track','Purchase',{value:1.00,currency:'AUD',content_name:'Leaderbored 10-credit pack'});}notice($('credit-status'),d.creditsGranted?d.creditsRemaining+' credits available. Payment verified.':'Payment is not yet confirmed. Complete the checkout, then verify again.');}
      catch(error){verified=false;notice($('credit-status'),error.message,true);}finally{verificationBusy=false;resetApproval();}
    };
    $('copy-receipt').onclick=async()=>{if(!receipt()){notice($('credit-status'),'Create a checkout or restore a private receipt first.',true);return;}try{await navigator.clipboard.writeText(receipt());notice($('credit-status'),'Receipt copied. Save it somewhere private; this page will not retain it.');}catch{notice($('credit-status'),'Clipboard unavailable. Copy the receipt privately from the field.',true);}};
    $('claim-idea').onclick=async()=>{
      if(!verified||!$('approve-credit').checked||busy)return;
      busy=true;update();
      // Reuse the identical tuple after timeouts. Never generate a new request ID
      // until a successful claim or explicit category/receipt change.
      const key=categoryId+':'+receipt();
      const pending=pendingClaims.get(key)||{categoryId,checkoutSessionId:receipt(),requestId:crypto.randomUUID()};
      pendingClaims.set(key,pending);
      try{
        let r=await request('leaderbored/claim',{...pending,approved:true});
        for(let attempt=0;r.status===202&&attempt<45;attempt++){
          notice($('idea-status'),'Flint is generating and checking a concept. No saved idea is assumed until the service confirms it.');
          await new Promise(resolve=>setTimeout(resolve,Math.max(2000,r.data.pollAfterMs||2000)));
          r=await request('leaderbored/claim',{...pending,approved:true,poll:true});
        }
        if(r.status===202)throw new Error('Still pending. Retry with the same category and receipt; the same request ID will be reused.');
        $('idea-output').prepend(renderIdea(r.data));notice($('idea-status'),'Saved. One credit was used. Back up your receipt to recover this idea later.');pendingClaims.delete(key);verified=false;
      }catch(error){notice($('idea-status'),error.message+' A retry here preserves the request ID; verify credits if needed.',true);}
      finally{busy=false;resetApproval();}
    };
    $('load-history').onclick=async()=>{
      if(busy||historyBusy)return;historyBusy=true;update();
      try{const {data:d}=await request('leaderbored/history',{checkoutSessionId:receipt()});$('idea-output').replaceChildren(...d.map(renderIdea));notice($('idea-status'),d.length?d.length+' saved ideas retrieved privately.':'No saved ideas for this receipt.');}
      catch(error){notice($('idea-status'),error.message,true);}finally{historyBusy=false;update();}
    };
    update();
  }
})();
`;
